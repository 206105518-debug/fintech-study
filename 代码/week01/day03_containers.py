# 题 5  主菜：用字典统计字频（就是昨天卡住的第四问）
#   三步法：
#     第一步  建一个空字典 counts = {}
#     第二步  遍历每个字：counts[ch] = counts.get(ch, 0) + 1
#             （取这个字当前的计数，取不到就当 0，再加一）
#     第三步  排序取前三：
#             sorted(counts.items(), key=lambda kv: kv[1], reverse=True)[:3]
# ==========================================================

text = "金融科技是用数据和技术改造金融业务的方向，数据是金融科技的基础。"

# TODO 5-1：去掉标点（，。）和空格，得到干净字符串
t1=text.replace("，","").replace("。","")
print(t1)
# TODO 5-2：用字典统计每个字出现的次数，打印整个字典
#卡住：还是不会
counts={}
for ch in t1: #ch即character 代表t1中的字
    counts[ch]=counts.get(ch,0)+1
print(counts)

# TODO 5-3：打印出现次数最多的 3 个字
#卡住：不会
s=sorted(counts.items(),key=lambda kv:kv[1],reverse=True)[:3] #参考
