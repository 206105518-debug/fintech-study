# drill_wordcount_step2.py ｜ 把「累计计数」拆成三个很小的台阶
#
# 你今天卡住的地方很具体：
#   你会写「有多少个不同的字」（set + len 那两行），但不会写「每个字各出现几次」。
#   这不是笨，这两个动作本来就不一样：
#     去重是「看不见重复」，算完就完了；
#     累计计数是「必须记住重复」，每多见一次都要回账本改数字。
#
# 下面三道小题用同一段文字，一步只加一个新东西。
# 每做完一步就运行一次，看到输出再往下改，不要一口气写完。

text = "宁德时代比亚迪宁德时代比亚迪宁德时代"


# ----------------------------------------------------------
# 步骤 A ｜ 先写一个「能跑但没在计数」的版本
#   要求：建一个空字典 counts，遍历 text 里的每一个字，
#         对每个字都做「让它等于 1」这一次赋值，然后打印字典。
#   你会看到：每个字都只记了 1，重复出现的字被后面的覆盖掉了。
#   这一步不用写对，目的只是让你亲眼看见：
#     字典的赋值是「覆盖」，不是「累加」。
# ----------------------------------------------------------
text = "宁德时代比亚迪宁德时代比亚迪宁德时代"
counts={}
for ch in text:
    counts[ch]=1
print(counts)


# ----------------------------------------------------------
# 步骤 B ｜ 把「覆盖」改成「累加」
#   现在的矛盾是：第二次见到同一个字时，我不想让它变成 1，
#                 我想让它变成「原来的数字 + 1」。
#   卡点在：第一次见到这个字时，字典里还没有它，
#           我拿不到「原来的数字」，那这时候该拿什么来加？
#   提示：字典有一个方法，作用是「去取值，取不到就给我一个兜底值」。
#         把上面这句话翻译成代码，就是这一题的全部。
#   自查：宁 / 德 / 时 / 代 各 3 次，比 / 亚 / 迪 各 2 次。
# ----------------------------------------------------------
text = "宁德时代比亚迪宁德时代比亚迪宁德时代"
counts={}
for ch in text:
    counts[ch]=counts.get(ch,0)+1
print(counts)


# ----------------------------------------------------------
# 步骤 C ｜ 加上排行
#   要求：用步骤 B 得到的 counts，打印出现次数最多的 3 个字。
#   难点：字典不能直接排序，要先把它变成一堆「字和次数」的配对，
#         再告诉排序函数按哪一项比大小。
#   自查：打印出来的三个字，每个的次数都应该是 3。
#         （四个字并列 3 次，谁被选中不唯一，别纠结）
# ----------------------------------------------------------
text = "宁德时代比亚迪宁德时代比亚迪宁德时代"
counts={}
for ch in text:
    counts[ch]=counts.get(ch,0)+1
print(counts)
print(counts.items())
print(sorted(counts.items()))
print(sorted(counts.items(),key=lambda kv:kv[1],reverse=True)[:3])

