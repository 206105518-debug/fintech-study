# 变式 1（3 分钟）同构练习：换个文本，把今天的流程从零再走一遍
#   要求：
#     1) 去掉标点和空格
#     2) 统计每个字出现的次数
#     3) 打印出现最多的 3 个字
#     4) 打印总共多少字、有多少个不同的字
#   自查：前三名应该是 宁 / 德 / 时，各出现 2 次
#         （三个并列，顺序不唯一，只要次数对就算过）
# ==========================================================

text1 = " 宁德时代和比亚迪都是新能源电池龙头，宁德时代和比亚迪的规模都很大。 "
t2=text1.replace("，","").replace("。","").replace(" ","")
counts={}
for ch in t2:
    counts[ch]=counts.get(ch,0)+1
print(counts)
print(sorted(counts.items(),key=lambda kv:kv[1],reverse=True)[:3])

word=set(t2)
print(word)
print(len(word)) #卡住：3）不会

# ==========================================================
# 变式 2（6 分钟）迁移练习：统计对象从「字」换成「词」
#   提示：split() 能把句子切成一个词的列表，后面的步骤和变式 1 完全一样
#   要求：打印出现最多的 2 个词
#   自查：应该是 数据 4 次、因子 3 次
# ==========================================================

text2 = "因子 因子 是 什么 因子 回测 回测 数据 数据 数据 数据"
t3=text2.split()
print(t3)
counts={}
for ch in t3:
    counts[ch]=counts.get(ch,0)+1
print(counts)
print(sorted(counts.items(), key=lambda kv:kv[1], reverse=True)[:2])
# ==========================================================
# 变式 3（6 分钟）反向练习：不给你文本，直接给你一个现成的字典
#   要求：
#     a) 打印次数最多的那个字（注意：只要那个字本身，不要连次数一起打印）
#     b) 打印次数最少的那些字
#     c) 打印所有次数等于 2 的字
#   自查：a 是 金；b 是 技 和 学；c 是 科 和 院
# ==========================================================

counts3 = {"金": 4, "融": 3, "科": 2, "技": 1, "学": 1, "院": 2}
counts4=sorted(counts3.items(),key=lambda kv:kv[1],reverse=True)
print(counts4)
