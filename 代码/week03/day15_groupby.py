#   一句话记住套路：**分组 → 聚合 → 得到一张新表**。

from pathlib import Path
import pandas as pd

BASE = Path(__file__).parent
csv_path = BASE.parent / "week01" / "hs300_sample.csv"
df = pd.read_csv(csv_path, encoding="utf-8", dtype={"代码": str})

# 样本里没有行业列，手工加一个。
# 真实工作里行业分类来自外部映射表，用字典 + map 加列是最常见的做法。
行业映射 = {
    "贵州茅台": "食品饮料", "五粮液": "食品饮料",
    "宁德时代": "电力设备", "隆基绿能": "电力设备",
    "比亚迪": "汽车",
    "招商银行": "银行", "平安银行": "银行",
    "中国平安": "非银金融", "中信证券": "非银金融", "东方财富": "非银金融",
    "紫金矿业": "有色金属",
    "恒瑞医药": "医药生物",
}
df["行业"] = df["名称"].map(行业映射)


# ==========================================================
# 题 1  第一次分组：按行业看平均
#   df.groupby("行业").mean()
#   它会自动做三件事：
#     1) 按行业把行分成几堆
#     2) 每堆算每一列的平均值（自动跳过文本列和缺失值）
#     3) 拼成一张新表，行标签变成行业名
#   动手：打印这张表
#   观察：这张表的行标签是什么？（提示：不是 0、1、2，而是行业名）
#   两个细节：文本列（名称）会被自动跳过；缺失值默认不参与计算。
# ==========================================================

# TODO 1
print(df.groupby("行业").mean(numeric_only=True).round(2))

# ==========================================================
# 题 2  agg：一个分组算多个统计量
#   a) 一次算多个函数：df.groupby("行业")["市盈率"].agg(["mean", "max", "count"])
#      count 是「有几个有效值」，能顺便看出哪一组有缺失
#   b) 不同列用不同函数：
#      df.groupby("行业").agg({"市盈率": "mean", "涨跌幅": ["mean", "std"]})
#   c) 自定义函数：df.groupby("行业")["市盈率"].agg(lambda s: s.max() - s.min())
#      这就是「组内极差」
#   动手：三个各跑一遍
#   观察 b 的结果：列名变成「双层」结构，像（市盈率, mean）这样
# ==========================================================

# TODO 2
print("一次算多个函数")
print(df.groupby("行业")["市盈率"].agg(["mean","max","count"]).round(2))

print("不同列用不同函数")
print(df.groupby("行业").agg({"市盈率":"mean", "涨跌幅":["mean","std"]}).round(2))

print("自定义函数")
print(df.groupby("行业")["市盈率"].agg(lambda s:s.max()-s.min()))

# ==========================================================
# 题 3  分组之后还能做三件事
#   a) 每组几行：df.groupby("行业").size()
#      和 count() 的区别：size 数行数（含缺失），count 数有效值
#   b) 只看某一组：df.groupby("行业").get_group("非银金融")
#   c) 按组筛选：df.groupby("行业").filter(lambda g: len(g) >= 2)
#      只留组内至少 2 行的组 —— 样本太少的组，统计没有意义
#   动手：三个各跑一遍，b 和 c 的结果都打印出来看看
# ==========================================================

# TODO 3
print("每组几行")
print(df.groupby("行业").size()) #返回一列
print(df.groupby("行业").count()) #返回表

print("只看某一组")
print(df.groupby("行业").get_group("非银金融"))

print("按组筛选")
print(df.groupby("行业").filter(lambda g: len(g)>=2))
print()
# ==========================================================
# 题 4  分档：把连续的数值切成几组（今天最实用的一个）
#   没有现成分类列时，要自己按数值分段。两种切法：
#     a) pd.cut(列, bins=[0, 15, 30, 100])   自己指定阈值（推荐，阈值有意义）
#     b) pd.qcut(列, q=3)                    按数量等分，每组只数一样多
#   金融里这两个术语你一定会遇到：按固定阈值分叫「等距分组」，
#   按数量分叫「等频分组」。因子回测最常用等频分组，
#   因为每组样本数一样，比较才公平。
#   动手：把股票按市盈率分成低估值 / 中估值 / 高估值三档：
#     df["估值档"] = pd.cut(df["市盈率"], bins=[0, 15, 30, 100],
#                           labels=["低估值", "中估值", "高估值"])
#   注意：市盈率缺失的那两只，分档结果是 NaN，它们不进任何一组。
#        这是缺失值的标准行为，和昨天你看到的一样。
# ==========================================================

# TODO 4

df["估值档"]=pd.cut(df["市盈率"],bins=[0,15,30,100],
                 labels=["低估值","中估值","高估值"])
print("分档结果")
print(df[["名称","市盈率","估值档"]])
print()
# ==========================================================
# 题 5  transform：把组内统计量加回原表
#   df["行业中位市盈率"] = df.groupby("行业")["市盈率"].transform("median")
#   它和 agg 的区别：
#     agg       每组算出一个数，结果是短表（几个组就是几行）
#     transform 把每组的数铺回原表每一行，结果和原表一样长
#   什么时候用：要拿「这只股票相对它行业的中位数」做比较时。
#   动手：加上这一列，再算一列「相对行业溢价 = 市盈率 / 行业中位市盈率 - 1」
# ==========================================================

# TODO 5
df["行业中位市盈率"] = df.groupby("行业")["市盈率"].transform("median")
df["相对行业溢价"]=(df["市盈率"]/df["行业中位市盈率"]-1).round(3)
print(df[["名称","市盈率","行业中位市盈率","相对行业溢价"]])
print()
# ==========================================================
# 主菜  做一张「分档汇总表」
