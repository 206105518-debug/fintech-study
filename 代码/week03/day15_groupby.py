# 今天学什么：
#   「把数据分成几堆，每堆算个数和平均值」——这就是分组聚合。
#   它在金融里无处不在：按行业看估值、按月份看收益、按评分档看违约率。
#   十一月你做多因子回测时的「分组回测」，用的就是这个套路。
