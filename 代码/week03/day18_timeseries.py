#   金融数据最特殊的一点是「有日期」。有了时间索引，你才能做
#   「按月看」「滚动 20 日看」「算日收益率」这些事。
#   今天三个动作：转成时间类型 → 设成索引 → 按时间聚合。

import numpy as np
import pandas as pd

np.random.seed(42)

# 先造一份 250 个交易日的模拟价格
# freq="B" 是 business day（工作日），造交易日数据的常用写法
dates = pd.date_range("2025-01-01", periods=250, freq="B")
daily_ret = np.random.normal(0.0003, 0.015, 250)
price = 100 * (1 + daily_ret).cumprod()
df = pd.DataFrame({"日期": dates, "收盘价": price})
print(df.head())
print()


# ==========================================================
# 题 1  把日期列转成真正的时间类型
#   从 date_range 造出来的列本来就是 datetime64，
#   但从 CSV 读进来的日期列是**字符串**，那样没法按时间聚合。
#   转换方法：pd.to_datetime(df["日期"])
#   动手：
#     a) 打印 df["日期"].dtype 看现在是什么
#     b) 用 astype(str) 造一列字符串日期，打印它的类型
#     c) 用 pd.to_datetime 转回来，再打印类型
#   记住：**时间序列的第一步永远是确认日期列是不是时间类型。**
# ==========================================================

# TODO 1
print(df["日期"].dtype)
as_str=df["日期"].astype(str)
print(f"字符串类型,{as_str.dtype}")
back=pd.to_datetime(as_str)
print(f"转回来，{back.dtype}")
print()
# ==========================================================
# 题 2  用日期当索引
#   df = df.set_index("日期")
#   设成索引之后可以：
#     df.loc["2025-03"]                    取 3 月全部
#     df.loc["2025-03-01":"2025-03-31"]    按区间取
#   动手：设索引，取出 3 月的行数
#   为什么时间要当索引：resample 要求索引是时间类型。
# ==========================================================

# TODO 2
df=df.set_index("日期")
print(len(df.loc["2025-03"]))
print()
print(df.loc["2025-03-01":"2025-03-31"])
print()
# ==========================================================
# 题 3  按月聚合（resample）
#   df.resample("ME").mean()
#   ME 是 month end（月末），按自然月分组再算平均。
#   ⚠️ 网上教程大量写的是 resample("M")，那是旧写法，
#      在 pandas 3 里已经不能用了，会直接报 ValueError。
#      照抄老教程会踩坑 —— 这也是为什么报错信息要认真读。
#   动手：按月算平均收盘价
#   自查：250 个工作日跨 2025 全年，应该有 12 行
# ==========================================================

# TODO 3
monthly=df.resample("ME").mean()
print(monthly)
print()
# ==========================================================
# 题 4  滚动窗口（rolling）—— 均线就是这么算的
#   df["收盘价"].rolling(20).mean()
#   意思是「每天往前看 20 天，算这 20 天的平均」。
#   前 19 天凑不满 20 个，结果是 NaN，这是正常的。
#   动手：算 20 日滚动均线，加成一列，打印前 22 行看 NaN 在哪
#   思考：均线本质是「平滑」，它把每天的波动抹平，所以**一定滞后**。
#        这一点以后读研报会反复遇到。
# ==========================================================

# TODO 4
df["20天均值"]=df["收盘价"].rolling(20).mean()
print(df["20天均值"])
print()

# ==========================================================
# 题 5  日收益率（pct_change）
#   df["收盘价"].pct_change()
#   算的是「今天 / 昨天 - 1」，第一行没有昨天，所以是 NaN。
#   动手：算出来加成一列，验证：
#     a) 第一行是不是 NaN
#     b) 最大单日涨幅、最大单日跌幅各是多少
#   提示：这是十一月算因子收益时最基础的一步。
# ==========================================================

# TODO 5
df["日收益率"]=df["收盘价"].pct_change()
print(df["日收益率"])
print(df["日收益率"].iloc[0])
print((df["日收益率"].max()*100).round(2))
print((df["日收益率"].min()*100).round(2))
print()
# ==========================================================
# 主菜  日频数据的三张脸
#   用上面这份 250 天的数据算出三样东西：
#     1) 月度平均收盘价（resample）
#     2) 20 日滚动均线（rolling）
#     3) 日收益率的均值和标准差（pct_change）
#   然后回答（写在下面）：
#     **这三个结果，哪个是「按时间聚合」、哪个是「按时间滚动」、
#      哪个是「相邻两期相减」？**
#   这三类操作覆盖了时间序列 90% 的日常需求。
# ==========================================================

# TODO 主菜
monthly=df["收盘价"].resample("ME").mean() #时间聚合
df["20 日滚动均线"]=df["收盘价"].rolling(20).mean() #时间滚动
df["日收益率"]=df["收盘价"].pct_change() #相邻两期相减

print(monthly,"行数",len(monthly))
print(df["20 日滚动均线"])
print((df["日收益率"].mean()*100).round(3),"%",(df["日收益率"].std()*100).round(3),"%")
