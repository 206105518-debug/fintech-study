print("====完整表====")
final_table=pd.merge(名单表, 行情表, on="代码", how="left")
final_table=final_table[["代码","名称","行业","权重","收盘价","涨跌幅","市盈率"]]
print(final_table)

final_table["涨跌幅*权重"]=final_table["涨跌幅"]*final_table["权重"]
分组=final_table.groupby("行业",observed=True).agg(
    权重合计=("权重","sum"), #新列名 = (对哪一列, 怎么算)
    加权涨跌=("涨跌幅*权重", lambda b: b.sum(min_count=1)),
)

分组["加权平均涨跌幅"]=(分组["加权涨跌"]/分组["权重合计"]).round(3)
