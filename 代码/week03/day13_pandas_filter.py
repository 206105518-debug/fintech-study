#
#   为什么要封装：以后你要试十几个不同的筛选条件，
#   写成一个函数，改参数就行，不用每次重抄一遍筛选代码。
#   这就是「可复用」在数据工作里的样子。
#
#   加分：函数里加一个 print，说明「用这些条件筛出来几只」，
#        以后调参数时一眼就知道筛得太松还是太紧。
# ==========================================================

# TODO 主菜
def screen(df, max_pe=30, min_change=0.0, min_amount=0.0):
    result=df[(df["市盈率"]<max_pe)&(df["涨跌幅"]> min_change)&(df["成交额"]>min_amount)]
    result=result.sort_values("市盈率",ascending=True)
    print(f"最终选股结果->筛选出来{len(result)}只")
    return result

print("主菜：同一数据，三组条件")
