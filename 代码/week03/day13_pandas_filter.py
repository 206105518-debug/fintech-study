# ==========================================================
# 题 1  多条件筛选
#   a) 单条件：df[df["涨跌幅"] > 0]
#   b) 两个条件同时满足（与）：df[(df["市盈率"] < 30) & (df["涨跌幅"] > 0)]
#   c) 满足任一即可（或）：df[(df["市盈率"] > 50) | (df["涨跌幅"] < -2)]
#   d) 取反：df[~(df["名称"] == "贵州茅台")]
#   e) 在名单里：df[df["名称"].isin(["贵州茅台", "比亚迪", "五粮液"])]
#
#   ⚠️ 三个坑，每个都要亲手踩一次：
#     1) 每个条件都要单独加括号。`&` 的优先级比 `>` 高，
#        不写括号会先算「30 & 涨跌幅」这种荒谬的东西，结果全错或直接报错。
#     2) 用 `&` `|` `~`，不能用 `and` `or` `not`。
#     3) 条件里的列名要写全：`df["市盈率"] < 30`，
#        写成 `df.市盈率` 在中文列名下会报错。
#
#   动手：五个各写一遍，每次打印「筛出来几只」
#   自查：上涨 6 只；市盈率<30 且上涨 3 只；高估值或大跌 2 只；排除茅台 11 只
# ==========================================================

