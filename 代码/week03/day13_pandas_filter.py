# ==========================================================
# 题 2  loc 与 iloc：按标签取 vs 按位置取
#   这是 pandas 里最容易混的一对，一句话记住：
#     **loc 认名字，iloc 认编号。**
#
#   a) df.loc[3]            —— 取「标签为 3」的那一行（就是第 4 行，因为标签从 0 开始）
#      df.iloc[3]           —— 取「第 4 个位置」的那一行（结果一样，但理由不一样）
#   b) 切片的差别（重点）：
#      df.loc[0:2]          —— 标签 0 到 2，**含右端**，3 行
#      df.iloc[0:2]         —— 位置 0 到 2，**不含右端**，2 行
#   c) 取具体格子：
#      df.loc[0, "名称"]     df.iloc[0, 1]     （第 1 行第 2 列）
#   d) 最实用的用法：把代码设成行标签，之后就能按代码取数
#      df2 = df.set_index("代码")
#      df2.loc["600519"]     —— 直接取出贵州茅台那一行
#
#   动手：a 到 d 各跑一遍，特别留意 b 里两种切片的行数
#   自查：loc[0:2] 是 3 行，iloc[0:2] 是 2 行 —— 差在右端
# ==========================================================

