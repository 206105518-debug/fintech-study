# pandas 是什么：
#   一句话——**Excel 的代码版**。它把整张表格装进一个叫 DataFrame 的对象里，
#   然后你可以用一行代码完成筛选、排序、统计、合并。
#
#   你在 day08 手写过「读 CSV、数行数、统计缺失、算均值」，
#   当时写了八十多行。用 pandas，同样的事八行就够。
#   今天你就来亲眼看这个对比。

from pathlib import Path
import pandas as pd


# ==========================================================
# 题 1  把文件读进来（顺便一劳永逸地解决路径问题）
#   数据文件还是 week01 里那份 hs300_sample.csv，12 行沪深300样本数据。
#
#   这次不用相对路径，改成「用脚本自己的位置去定位文件」：
#     BASE = Path(__file__).parent        # 这个脚本所在的目录（week03）
#     csv_path = BASE.parent / "week01" / "hs300_sample.csv"
#   这样写的好处：**不管你从哪个目录运行脚本，它都能找到文件**。
#   你已经被路径坑过两次了，从这个文件开始，养成这个写法。
#
#   然后用 pd.read_csv(csv_path) 读进来，打印出来看看。
#   会打印成一个行列对齐的表格 —— 这就是 DataFrame。
#
#   ⚠️ 读完别急着往下走，先盯着「代码」这一列看三秒。
#      你文件里写的是 000858、002594、000001，
#      屏幕上显示的是什么？**前导零去哪了？**
#      原因：pandas 看到这一列全是数字，就自作主张把它读成了整数。
#      而股票代码是**编号**，不是数量 —— 000858 和 858 不是一回事，
#      就像身份证号、手机号不能当数字算一样。
#      修法：读的时候明确告诉它这一列是文本：
#        df = pd.read_csv(csv_path, dtype={"代码": str})
#      这是你在 day08 撞过的那个「代码列不该算均值」的坑，
#      在 pandas 里换了个形式又出现了。
# ==========================================================

# TODO 1
BASE = Path(__file__).parent
csv_path = BASE.parent / "week01" / "hs300_sample.csv"
df = pd.read_csv(csv_path, dtype={"代码": str}) #df即dataframe
print(df)

# ==========================================================
# 题 2  看数据：六个命令建立第一印象
#   拿到任何一份数据，先跑这几条：
#     df.head()      前 5 行（看长什么样）
#     df.shape       多少行多少列
#     df.columns     有哪些列名
#     df.dtypes      每一列是什么类型
#     df.info()      一次看全：行列数、列名、类型、非空个数
#     df.describe()  数值列的统计摘要：个数、均值、标准差、最小最大、四分位
#   特别看两件事：
#     1) dtypes 里数字列是 int64 / float64，还是 object（文本）？
#     2) info 里的非空个数 —— 和总行数对不上，就说明有缺失
# ==========================================================

# TODO 2
print("前五行")
print(df.head())

print("有多少行，多少列")
print(df.shape)

print("有哪些列名")
print(df.columns)

print("每一列是什么类型")
print(df.dtypes)

print("一次看全：行列数、列名、类型、非空个数")
print(df.info())

print("数值列的统计摘要：个数、均值、标准差、最小最大、四分位")
print(df.describe())

# ==========================================================
# 题 3  选一列 vs 选多列（pandas 最基础的分叉）
#   a) 选一列：df["收盘价"]  → 返回 Series（可以理解成「一列」）
#      它有自己的 mean()、max()、sort_values() 等方法
#   b) 选多列：df[["代码", "名称", "收盘价"]]  → 返回 DataFrame（还是一张表）
#      注意里面是**双层方括号**：外层取下标，内层是列表
#   动手：两种各打印一次，看它们在屏幕上长得有什么不一样
#   （Series 没有列名那一行，DataFrame 有）
# ==========================================================

# TODO 3
print("选一列")
print(df["收盘价"])

print("选多列")
print(df[["代码", "名称", "收盘价"]])

# ==========================================================
# 题 4  筛选与排序（今天最实用的两个动作）
#   a) 单条件：df[df["涨跌幅"] > 0]          涨的股票
#   b) 多条件：df[(df["市盈率"] < 30) & (df["涨跌幅"] > 0)]
#      两个坑：每个条件都要加括号；用 & 不用 and
#   c) 排序：df.sort_values("收盘价", ascending=False)
#   d) 取前几名：df.nlargest(3, "成交额")
#   动手：挑出「市盈率低于 30 且涨跌幅为正」的股票，按收盘价从高到低排好打印
#   思考：这个筛选条件像不像选股？周五的实战你会做更接近真实的事
# ==========================================================

# TODO 4
print("单条件")
print(df[df["涨跌幅"]>0])

print("多条件")
print(df[(df["市盈率"]<30)&(df["涨跌幅"]>0)])

print("排序")
print(df.sort_values("收盘价", ascending=False))

print("取前3名")
print(df.nlargest(3,"成交额"))

picked=df[(df["市盈率"]<30)&(df["涨跌幅"]>0)]
picked=picked.sort_values("收盘价",ascending=False)
print(picked)

# ==========================================================
# 题 5  存出去
#   df.to_csv("文件名.csv", index=False, encoding="utf-8-sig")
#   两个参数要记住：
#     index=False —— 不要把行号也存进去（不然会多出一列没用的数字）
#     encoding="utf-8-sig" —— 存 CSV 时用这个编码，Excel 打开中文才不乱码
#   动手：把题 4 筛出来的结果存成 picked.csv，然后去文件夹里确认它存在
# ==========================================================

# TODO 5
df.to_csv("picked.csv", index=False, encoding="utf-8-sig")
print("已保存")

