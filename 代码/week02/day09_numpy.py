# 题 5  统计函数与 axis（axis 是今天的难点）
#   一维直接算：arr.mean()、arr.std()、arr.max()、arr.min()、
#              np.percentile(arr, 50)  ← 中位数
#   二维要指定方向：
#     m.mean(axis=0)  按列算 → 每一列一个结果
#     m.mean(axis=1)  按行算 → 每一行一个结果
