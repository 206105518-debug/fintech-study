#卡住：参考答案
def total_return(nav):
    return nav[-1] - 1

def annual_return(nav):
    cum_return =nav[-1] - 1
    return (1 + cum_return ) ** (252 / len(nav)) - 1

def annual_volatility(returns):
    return returns.std() * np.sqrt(252)

def max_drawdown(nav):
    日回撤 = nav /np.maximum.accumulate(nav) - 1
    return 日回撤.min()

