import numpy as np


# ==========================================================
# 题 1  生成 500 天的日收益率
#   假设这只基金的长期年化收益 10%、年化波动 20%，一年 252 个交易日。
#   要先生成日频的两个参数：
#     日收益率均值 = 年化收益 / 252
#     日收益率标准差 = 年化波动 / √252
#   然后用 np.random.normal(均值, 标准差, 500) 生成 500 个日收益率。
#   别忘了 np.random.seed(42) —— 可复现是底线。
#   动手：生成后打印前 5 个值，看看它们大概是什么量级（应该在 ±0.02 附近）
# ==========================================================

# TODO 1
np.random.seed(42)
a=0.1/252      # %是取余 /是除
b=0.2/(252**0.5)
returns=np.random.normal(a,b,500)
print(f"日收益率是{returns[:5]}")
#卡住：怎么只打印5个值
#日收益率前 5 个：[ 0.00665484 -0.00134514  0.00855693  0.0195852  -0.00255323]

# ==========================================================
# 题 2  从日收益率到净值曲线
#   净值的意思是「一元钱今天值多少」。
#   第一天赚 1%，净值就是 1.01；第二天再赚 1%，净值是 1.01 × 1.01。
#   所以净值不是相加，是**累乘**：
#     净值 = (1 + 日收益率).cumprod()
#   动手：算出净值曲线，打印它的第一个值和最后一个值。
#   自查：最后一个值就是「当初的 1 元变成了多少元」，
#        如果是 1.2，就是两年赚了 20%
#        （种子为 42 时：最后一天约 1.2255）
# ==========================================================

# TODO 2
nav = (1 + returns).cumprod()
print(f"第一个值是{nav[0]:.4f}")
print(f"最后一个值是{nav[-1]:.4f}")

#第一个值是1.0067,最后一个值是1.2255

# ==========================================================
# 题 3  累计收益率
#   累计收益率 = 净值最后一天 - 1
#   这个最直白：从 1 变成 1.2，累计收益就是 0.2，也就是 20%。
#   动手：算出累计收益率，用百分比打印
#   自查（种子 42）：约 22.5%
# ==========================================================

# TODO 3
cum_return = nav[-1] - 1
print(f"累计收益率是{cum_return *100:.2f}%")
#如何用百分比打印

# ==========================================================
# 题 4  年化收益率（这里是今天的第一个思考点）
#   500 个交易日大约是 2 年。两年赚 20%，年化不是 10%，
#   而是 (1 + 20%) 开平方 - 1，因为收益是**复利**累积的。
#   公式：年化收益率 = (1 + 累计收益率) ** (252 / 天数) - 1
#   为什么不直接除以年数：因为钱会滚钱，
#   第一年赚的钱在第二年也帮你赚，所以要开方，不能除。
#   动手：算出来，用百分比打印
#   自查：因为生成时用的年化是 10%，你的结果应该在 10% 附近，
#        但**不会正好等于 10%** —— 随机路径本来就偏离，
#        这是正常现象，不是代码写错了
#        （种子 42 时约 10.8%）
# ==========================================================

# TODO 4
ann_net = (1 + cum_return ) ** (252 / 500) - 1
print(f"年化收益率是{ann_net *100:.1f}%")

# ==========================================================
# 题 5  年化波动率
#   波动率就是收益率的标准差，衡量「抖得厉害不厉害」。
#   日频的标准差要换成年度口径，要乘 √252：
#     年化波动率 = 日收益率.std() * √252
#   为什么是乘 √252 而不是乘 252：因为方差可以相加，
#   而波动率是方差开根号，所以时间要开根号。
#   （想不明白先记结论，周六我给你推导一遍——面试会考这个）
#   动手：算出来，用百分比打印
#   自查：生成时用的是 20%，你的结果应该在 20% 附近
#        （种子 42 时约 19.6%）
# ==========================================================

# TODO 5
ann_vol  = returns.std() * np.sqrt(252)
print(f"年化波动率是{ann_vol*100:.1f}%")

# ==========================================================
# 题 6  最大回撤（今天最实用的一个）
#   回撤的意思是：从历史最高点算起，现在跌了多少。
#   分三步：
#     1) 历史最高净值：np.maximum.accumulate(nav)
#        —— 逐日向前看，记住「到目前为止的最高点」
#     2) 每一天的回撤 = 当日净值 / 当日最高净值 - 1
#        —— 永远小于等于 0
#     3) 最大回撤 = 上面这一串里的最小值
#   动手：算出来，用百分比打印
#   自查：**最大回撤必须是负数或 0**。如果你算出一个正数，
#        一定是公式写反了（比如写成了 最高净值 / 当日净值 - 1）
#        （种子 42 时约 -17.8%）
#   顺便想一想：为什么机构这么在意回撤？
#       （提示：净值从 1 跌到 0.5 是跌 50%，但从 0.5 涨回 1 要涨 100%）
# ==========================================================

# TODO 6
历史最高净值=np.maximum.accumulate(nav)
日回撤 = nav / 历史最高净值 - 1
最大回撤=日回撤.min()
print(f"最大回撤是{最大回撤*100:.1f}%")



