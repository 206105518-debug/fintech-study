# 主菜  把四个指标封装成函数
#   写四个函数，每个只做一件事：
#     total_return(nav)      → 累计收益率
#     annual_return(nav)     → 年化收益率（需要知道天数，天数就是 len(nav)）
#     annual_volatility(returns) → 年化波动率
#     max_drawdown(nav)      → 最大回撤
#   然后用它们把结果打印成一张表，像这样：
#     指标              数值
#     累计收益率        12.34%
#     年化收益率         6.10%
#     年化波动率        19.80%
#     最大回撤         -18.20%
#   为什么非要封装成函数：
#     明天画图、十一月做多因子回测，调用的都是这几个函数；
#     而且每个函数写清注释以后，就是你面试时能讲出来的东西。
#   加分：给每个函数写一行 docstring，说明输入什么、返回什么。
