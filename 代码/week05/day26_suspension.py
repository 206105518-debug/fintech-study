def align_to_calendar(df, calendar):
    out=[]
    for code, g in df.groupby("股票代码"):
        g = g.set_index("日期").reindex(calendar)
        g["股票代码"] = code
        g["是否停牌"] = g["收盘"].isna()
        g = g.reset_index().rename(columns={"index": "日期"})
        out.append(g)
    return pd.concat(out, ignore_index=True)

