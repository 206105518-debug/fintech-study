# 题 4  两种处理方式，对收益率的影响
#   a) 方案 A：不做任何填充，停牌日就是 NaN
#   b) 方案 B：前值填充收盘价（ffill），成交量填 0
#   对两种方案各算一次日收益率（pct_change），然后看三样：
#     - 方案 B 里，停牌日的收益率是多少？（0）
#     - 区间首尾收益：两种方案会不会不同？（很可能相同——ffill 不改首尾价）
#     - **日收益率的标准差：两种方案差多少？**
#       （这才是 ffill 真正的影响：多出一堆 0 收益日，把波动率摊薄）
#   动手：用一只 2025 年中段停牌较久的股票试（比如 600930 上市前不算，
