#       把 DataFrame 按「股票代码」分组，每组 reindex 到 calendar，
#       补齐后加三列：
#         股票代码（补回来）、是否停牌（原始行是否缺失）、日期（索引还原）
#       返回补齐后的长表
#   提示：
